def regime_groups() -> list[dict[str, Any]]:
    """대분류 1개 = 그룹 1개. 세부 그룹의 검색어를 합쳐 만든다 (그룹당 20어 상한)."""
    out: list[dict[str, Any]] = []
    for regime, subs in KEYWORD_SETS.items():
        merged: list[str] = []
        for sub in subs:
            for kw in sub["keywords"]:
                if kw not in merged:
                    merged.append(kw)
        if len(merged) > 20:
            raise ValueError(f"{regime}: 검색어 {len(merged)}개 — 그룹당 20개 상한 초과")
        out.append({"groupName": regime, "keywords": merged})
    return out


def sub_groups() -> list[tuple[str, dict[str, Any]]]:
    """(대분류, 세부 그룹) 목록."""
    return [(regime, sub) for regime, subs in KEYWORD_SETS.items() for sub in subs]
