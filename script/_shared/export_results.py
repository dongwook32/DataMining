"""Collect the stored paper's tables, figures and Excel workbooks with provenance."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil

from util.paths import ROOT, RESULTS, PAPER, BASELINE


def copy_sources(sources, destination):
    destination = Path(destination).resolve()
    checked = []
    for source, relative in sources:
        source = Path(source).resolve()
        target = (destination / relative).resolve()
        if not target.is_relative_to(destination) or target == source:
            raise ValueError(f'출력 경로가 원본과 겹치거나 저장 폴더를 벗어납니다: {target}')
        if not source.is_file():
            raise FileNotFoundError(source)
        checked.append((source, target))
    records = []
    for source, target in checked:
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
        if hashlib.sha256(target.read_bytes()).hexdigest() != source_hash:
            raise ValueError(f'사본 해시 불일치: {target}')
        records.append({'source': source.relative_to(ROOT).as_posix() if source.is_relative_to(ROOT) else str(source),
                        'output': target.relative_to(destination).as_posix(),
                        'sha256': source_hash, 'bytes': target.stat().st_size})
    return records


def run(output_dir=None):
    from core.excel_export import baseline_sources, export_results, PROCESSED

    destination = Path(output_dir).resolve() if output_dir else RESULTS / 'paper'
    # Sources are immutable inputs to this packaging operation.
    for protected in (ROOT / 'data', ROOT / 'output', ROOT / 'docs', ROOT / 'core', ROOT / 'collector'):
        if destination.is_relative_to(protected) or protected.is_relative_to(destination):
            raise ValueError('정리 출력은 원본 데이터·논문·코드 폴더와 별도 위치를 사용하세요.')
    learning, supplemental = baseline_sources()
    sources = []
    seen = set()
    for source, _ in learning + supplemental:
        if source in seen:
            continue
        seen.add(source)
        relative = source.relative_to(PROCESSED) if source.is_relative_to(PROCESSED) else Path('replication') / source.name
        sources.append((source, Path('tables') / relative))
    for name in ('topic_map.csv', 'regime_monthly.csv',
                 'forecast.csv'):
        sources.append((PROCESSED / 'reactions' / name, Path('tables/regimes') / name))
    sources += [(p, Path('figures') / p.name) for p in sorted((PAPER / 'figures').glob('*.png'))]
    sources += [(p, Path('validation') / p.name) for p in sorted((PAPER / 'replication').glob('S*.md'))]
    audit = PROCESSED / 'reactions/audit.json'
    sources.append((audit, Path('validation') / audit.name))

    # Validate source presence before generating any output.
    for source, _ in sources:
        if not source.is_file():
            raise FileNotFoundError(source)
    workbooks = export_results(PROCESSED / 'models' / 'base', audit,
                               destination / 'excel', paper_run=True)
    records = copy_sources(sources, destination)
    for path in workbooks:
        records.append({'source': 'generated by core.excel_export from stored paper run',
                        'output': path.relative_to(destination).as_posix(),
                        'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'bytes': path.stat().st_size})
    manifest = {'run_id': BASELINE, 'created_utc': datetime.now(timezone.utc).isoformat(),
                'purpose': '기준 논문 저장 결과 정리; 새 학습 결과가 아님', 'files': records}
    (destination / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    (destination / 'README.md').write_text(
        '# 최종 논문 결과\n\n'
        f'기준 실행: `{BASELINE}`. `python -m core.run_all`로 검산 후 정리합니다.\n\n'
        '- `excel/`: 전처리·학습, 중간 분석·검증, 최종 결과 엑셀 3개\n'
        '- `tables/`: 분석별 CSV 사본\n- `figures/`: 논문 그림\n'
        '- `validation/`: 재현 안내와 기준 실행 감사 기록\n'
        '- `manifest.json`: 각 파일의 원본 위치·SHA-256·크기\n\n'
        '원자료와 학습 모델은 기존 `data/`에 보존하며 이 폴더에 중복 복사하지 않습니다.\n', encoding='utf-8')
    print(f'정리 완료: {destination} ({len(records)}개 산출물)', flush=True)
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path)
    args = parser.parse_args()
    run(args.output_dir)


if __name__ == '__main__':
    main()
